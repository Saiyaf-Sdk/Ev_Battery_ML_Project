"""Member C: one-time final test evaluation of a locked, calibrated model.

No fitting, threshold tuning or model selection occurs in this module.
"""
from __future__ import annotations

import argparse
from datetime import datetime, timezone
import json
from pathlib import Path

import joblib
import numpy as np

from .config import RANDOM_STATE, TARGET
from .data import load_dataset, make_features, split_data
from .evaluation import evaluate
from .member_c import checksum


def finalize(data_path: Path, staged_path: Path, outdir: Path) -> dict:
    data_path, staged_path, outdir = map(Path, (data_path, staged_path, outdir))
    final_path = outdir / "model.joblib"
    metrics_path = outdir / "test_metrics.json"
    metadata_path = outdir / "metadata.json"

    # Avoid accidental repeats or overwriting another member's final model.
    existing = [p for p in (final_path, metrics_path, metadata_path) if p.exists()]
    if existing:
        raise FileExistsError(
            "Final output already exists; do not rerun or overwrite after opening the test set: "
            + ", ".join(map(str, existing))
        )

    # joblib is pickle-based: load ONLY files generated by your own trusted team.
    staged = joblib.load(staged_path)
    meta = dict(staged["metadata"])
    if meta.get("final_test_evaluated") is not False:
        raise ValueError("The staged model has already been marked as test-evaluated")
    if meta.get("fast_smoke_test_only") is not False:
        raise ValueError("Smoke-test or unknown model settings cannot be finalized")
    if meta.get("include_suspect_scores") is not False:
        raise ValueError("Model includes suspect composite scores")
    if meta.get("training_data_sha256") != checksum(data_path):
        raise ValueError("CSV checksum differs from the staged model's training data")
    if meta.get("calibration_method") != "sigmoid":
        raise ValueError("Unexpected calibration method")

    threshold = float(staged["threshold"])
    if not np.isfinite(threshold) or not 0 < threshold < 1:
        raise ValueError("Invalid previously selected threshold")
    if float(meta["threshold"]) != threshold:
        raise ValueError("Staged metadata and model have different thresholds")

    df = load_dataset(data_path)
    # No selections or fitting below: we only evaluate the frozen model once.
    test = split_data(df, seed=RANDOM_STATE).test
    x_test = make_features(test, include_suspect_scores=False, drop_redundant=True)
    expected_features = list(meta["engineered_feature_columns"])
    if list(x_test.columns) != expected_features:
        raise ValueError("Test feature schema differs from the frozen training model")
    y_test = test[TARGET].astype(int)
    probabilities = staged["model"].predict_proba(x_test)[:, 1]
    if not np.isfinite(probabilities).all() or np.any((probabilities < 0) | (probabilities > 1)):
        raise ValueError("Model returned invalid probabilities")
    metrics = evaluate(y_test, probabilities, threshold)

    meta.update({
        "task": "synthetic_EV_battery_failure_classification_NOT_verified_forecasting",
        "seed": RANDOM_STATE,
        "created_utc": datetime.now(timezone.utc).isoformat(),
        "test_n": len(test),
        "test_failures": int(y_test.sum()),
        "final_test_evaluated": True,
        "evaluation_warning": "Synthetic cross-sectional dataset; no proven prediction lead time or real-world safety validation.",
    })
    final_bundle = {
        "model": staged["model"],
        "threshold": threshold,
        "metadata": meta,
    }

    outdir.mkdir(parents=True, exist_ok=True)
    # Write a single finalized bundle; never alter the staged calibration artifact.
    joblib.dump(final_bundle, final_path)
    metrics_path.write_text(json.dumps(metrics, indent=2, allow_nan=False), encoding="utf-8")
    metadata_path.write_text(json.dumps(meta, indent=2, allow_nan=False), encoding="utf-8")

    print("Final evaluation complete (one-time held-out test).")
    print(f"Model: {meta['winner']} | Frozen threshold: {threshold:.2f}")
    print(f"Test rows: {metrics['n']} | Actual failures: {metrics['failures']}")
    for name in ("average_precision", "roc_auc", "brier_score", "precision", "recall", "f1", "f2"):
        print(f"{name}: {metrics[name]:.4f}")
    print(f"TP={metrics['tp']} FP={metrics['fp']} TN={metrics['tn']} FN={metrics['fn']}")
    print(f"Saved final model: {final_path}")
    return metrics


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--data", type=Path, default=Path("data/ev_battery.csv"))
    parser.add_argument("--staged-model", type=Path,
                        default=Path("artifacts/member_c/staged_model.joblib"))
    parser.add_argument("--outdir", type=Path, default=Path("artifacts"))
    args = parser.parse_args()
    finalize(args.data, args.staged_model, args.outdir)


if __name__ == "__main__":
    main()
